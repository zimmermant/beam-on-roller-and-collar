// Zero-dependency inliner. Modules are concatenated into one scope, so the build FAILS on duplicate top-level
// names rather than silently shadowing them.
import { readFileSync, writeFileSync, mkdirSync, readdirSync, unlinkSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { Script } from 'node:vm';

const root = dirname(fileURLToPath(import.meta.url));
const SRC = join(root, 'src');

// ---- CONFIG: the only part to edit for a new simulation -------------------------------------------------
// Dependency order. app.js runs last because it touches the DOM immediately.
export const MODULES = ['format.js', 'fields.js', 'physics.js', 'layout.js', 'svg.js', 'state.js', 'presets.js', 'scene.js', 'controls.js', 'interact.js', 'app.js'];

// One page: the four diagrams and the applied-couple slider.
export const PAGES = [
  { name: 'main', out: 'beam_roller_collar.html', template: 'index.template.html', css: ['styles.css'], modules: MODULES }
];

export const BUDGET_BYTES = 250_000;   // per page, measured in BYTES (Buffer.byteLength), not characters

// Every page this script writes carries this comment, so a later build can tell its own output from other files:
// a page renamed in PAGES leaves the old .html behind, and main() deletes it (only .html files that carry the marker).
export const BUILD_MARKER = '<!-- generated by build.js: do not edit this file, edit src/ and rebuild -->';
// ---------------------------------------------------------------------------------------------------------

// Anchored at column 0 on purpose. Every top-level declaration in src/ starts there, and matching leading
// whitespace too would flag ordinary function-local `const`s as collisions and fail the build for no reason.
const DECL = /^(?:export\s+)?(?:async\s+)?(?:function|const|let|var|class)\s+([A-Za-z_$][\w$]*)/;

// A column-0 const/let/var immediately destructured (`const { a } = …`) declares names DECL cannot extract. Treat it
// as a hard build error so a human names it explicitly instead of it silently shadowing in the shipped bundle.
const DESTRUCTURE = /^(?:export\s+)?(?:const|let|var)\s+[\[{]/;

// An import that RENAMES what it brings in -- `import { coupleArc as geometry }` -- cannot survive
// inlining: every module ends up in one scope and the import line is stripped, so the new name never
// exists and the module fails at run time with a ReferenceError the node tests cannot see, because
// node honours the alias. Caught here instead, at build time, with the name to use said out loud.
const IMPORT_ALIAS = /^\s*import\s*\{[^}]*\b(\w+)\s+as\s+(\w+)/m;

// A column-0 const/let/var whose declared name starts an identifier. DECL only captures the FIRST declarator of a
// statement, so `export const A = 1, B = 2;` registers A and silently drops B. Combined with hasTopLevelComma
// below, this hard-fails any column-0 statement that declares more than one name.
const MULTI_DECL = /^(?:export\s+)?(?:const|let|var)\s+[A-Za-z_$]/;

// True if `line` contains a comma outside any string literal and outside any (), [] or {} nesting -- a comma that
// separates top-level declarators rather than one inside an object/array literal or a call's arguments.
function hasTopLevelComma(line) {
  let depth = 0, quote = null;
  for (let i = 0; i < line.length; i++) {
    const c = line[i];
    if (quote) {
      if (c === '\\') { i++; continue; }        // skip escaped char, incl. escaped quote
      if (c === quote) quote = null;
      continue;
    }
    // A trailing `//` comment is not code: "export const D = 250; // a, b" has one declarator.
    if (c === '/' && line[i + 1] === '/') break;
    if (c === '"' || c === "'" || c === '`') { quote = c; continue; }
    if (c === '{' || c === '[' || c === '(') depth++;
    else if (c === '}' || c === ']' || c === ')') depth--;
    else if (c === ',' && depth === 0) return true;
  }
  return false;
}

export function strip(code) {
  // Drop relative imports as whole statements rather than line-by-line: an import whose named list wraps onto a
  // second line has no "from" on its opening line, so a per-line filter never sees it. [^;]* cannot cross the
  // statement's own semicolon, so this cannot run away into later code.
  code = code.replace(/^\s*import\s[^;]*from\s+['"]\.\/[^'"]+['"]\s*;?[ \t]*$/gm, '');
  return code.split('\n')
    .filter(l => !/^\s*export\s*\{[^}]*\}\s*;?\s*$/.test(l))
    .map(l => l.replace(/^(\s*)export\s+(function|const|let|var|class)\s/, '$1$2 '))
    .join('\n');
}

// Scans one module's source line by line, registering each column-0 declared name into `seen` (shared across the
// page's modules), and throws on a duplicate name, a destructuring declaration or a multi-declarator statement.
export function scanForDuplicates(code, moduleName, seen) {
  for (const line of code.split('\n')) {
    if (DESTRUCTURE.test(line)) {
      throw new Error(
        `Top-level destructuring declaration in ${moduleName} cannot be checked for name collisions: ` +
        `"${line.trim()}". Rewrite it as a named const/let/var so the duplicate-name detector can see the name(s).`);
    }
    if (MULTI_DECL.test(line) && hasTopLevelComma(line)) {
      throw new Error(
        `Multi-declarator top-level declaration in ${moduleName} cannot be fully checked for name collisions: ` +
        `"${line.trim()}". Split it into one name per statement so the duplicate-name detector can see every name.`);
    }
    const hit = DECL.exec(line);
    if (hit) {
      const name = hit[1];
      if (seen.has(name)) {
        throw new Error(
          `Duplicate top-level name "${name}" in ${moduleName}; already declared in ${seen.get(name)}. ` +
          `All modules share one scope after inlining, so names must be unique.`);
      }
      seen.set(name, moduleName);
    }
  }
  return seen;
}

// Builds one page to a string: the checks that need the page alone all happen here, so a page that fails never
// reaches the disk (main() writes only after every page has passed).
function buildPage(page) {
  const seen = new Map();
  const parts = [];
  for (const m of page.modules) {
    const code = readFileSync(join(SRC, m), 'utf8');
    const alias = code.match(IMPORT_ALIAS);
    if (alias) {
      throw new Error(`Renaming import in ${m}: "${alias[1]} as ${alias[2]}". Every module shares one ` +
        `scope after inlining and the import line is removed, so "${alias[2]}" would never exist. ` +
        `Use "${alias[1]}" directly, or rename it at its definition.`);
    }
    scanForDuplicates(code, m, seen);
    parts.push(`// ===== ${m} =====\n` + strip(code));
  }

  const js = `(function () {\n"use strict";\n${parts.join('\n')}\n})();`;

  // Every assertion below is a regex over text, while strip() does two non-trivial rewrites. Actually parsing the
  // assembled bundle turns a class of stripping bugs into a loud build failure instead of a silently broken file.
  try {
    new Script(js);
  } catch (err) {
    throw new Error(
      `Build failed: the ${page.name} page's assembled bundle does not parse as JavaScript.\n  - ${err.message}`);
  }

  const css = page.css.map(f => readFileSync(join(SRC, f), 'utf8')).join('\n');

  let html = readFileSync(join(SRC, page.template), 'utf8');
  if (!html.includes('<!--INLINE_CSS-->') || !html.includes('<!--INLINE_JS-->')) {
    throw new Error(`${page.template} is missing one of its inline markers`);
  }
  // A plain string replacement expands $&, $`, $', $$ and $n in the REPLACEMENT text. A function replacement is
  // spliced in verbatim, so a `$&` anywhere in the CSS or a module cannot silently corrupt the bundle.
  html = html.replace('<!--INLINE_CSS-->', () => `${BUILD_MARKER}\n<style>\n${css}\n</style>`)
             .replace('<!--INLINE_JS-->', () => `<script>\n${js}\n</script>`);

  // Build-time assertions: the artifact must be genuinely self-contained.
  const problems = [];
  if (/^\s*import\s/m.test(js)) problems.push('an import statement survived');
  if (/^\s*export\s/m.test(js)) problems.push('an export statement survived');
  // svg.js declares NS = 'http://www.w3.org/2000/svg', the XML namespace string createElementNS needs: a fixed
  // identifier, never fetched. It is the only URL allowed; any other (CDN script, web font, <img src>) fails.
  const SVG_NS = 'http://www.w3.org/2000/svg';
  if (/https?:\/\//.test(html.split(SVG_NS).join(''))) problems.push('an external URL is present');
  if (/<script[^>]+src=/.test(html)) problems.push('an external script tag is present');
  if (/<link[^>]+href=/.test(html)) problems.push('an external stylesheet is present');
  // Bytes, not characters: a page full of multi-byte characters (−, ·, ½, —) is bigger on the wire than .length says.
  const bytes = Buffer.byteLength(html, 'utf8');
  if (bytes > BUDGET_BYTES) problems.push(`output is ${bytes} bytes, over the 250 KB budget`);
  if (problems.length) throw new Error(`Build failed (${page.name} page):\n  - ` + problems.join('\n  - '));
  return html;
}

// Deletes the .html files in `dir` that this build wrote on an earlier run but no longer produces: a name that is not
// in PAGES, ends in .html and carries BUILD_MARKER. Anything else in the folder (a hand-written page, a .txt, a
// .html without the marker) is never touched. Returns the names removed.
function removeStale(dir, label) {
  const keep = new Set(PAGES.map(p => p.out));
  const removed = [];
  for (const name of readdirSync(dir)) {
    if (!name.endsWith('.html') || keep.has(name)) continue;
    if (!readFileSync(join(dir, name), 'utf8').includes(BUILD_MARKER)) continue;
    unlinkSync(join(dir, name));
    removed.push(name);
    console.log(`removed stale ${label}/${name} (an earlier build's page that is no longer in PAGES)`);
  }
  return removed;
}

// outDir lets a test point the build at a scratch directory outside the repo instead of dist/.
export function main(outDir) {
  const built = PAGES.map(page => ({ page, html: buildPage(page) }));

  const dir = outDir || join(root, 'dist');
  mkdirSync(dir, { recursive: true });
  for (const { page, html } of built) {
    writeFileSync(join(dir, page.out), html);
    const label = outDir ? join(outDir, page.out) : `dist/${page.out}`;
    console.log(`built ${label}  (${Buffer.byteLength(html, 'utf8')} bytes, ${page.modules.length} modules)`);
  }
  removeStale(dir, outDir || 'dist');
}

// Run only when this file is the program node was invoked on, so a test can import build.js without building.
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main();
}
